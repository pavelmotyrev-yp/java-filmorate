package ru.yandex.practicum.filmorate.repository.user;

import ru.yandex.practicum.filmorate.model.User;

import java.util.Collection;
import java.util.List;
import java.util.Optional;

/**
 * Интерфейс хранилища пользователей.
 * Предоставляет методы для CRUD-операций и управления дружбой.
 */
public interface UserStorage {

    /**
     * Создаёт нового пользователя и присваивает ему уникальный идентификатор.
     *
     * @param user пользователь для создания
     * @return созданный пользователь с присвоенным идентификатором
     */
    User create(User user);

    /**
     * Обновляет данные существующего пользователя.
     *
     * @param id идентификатор пользователя для обновления
     * @param user новые данные пользователя
     * @return обновлённый пользователь
     */
    User update(long id, User user);

    /**
     * Получает пользователя по уникальному идентификатору.
     *
     * @param id идентификатор пользователя
     * @return Optional с пользователем, если он найден
     */
    Optional<User> get(long id);

    /**
     * Возвращает коллекцию всех пользователей.
     *
     * @return коллекция всех пользователей
     */
    Collection<User> getAll();

    /**
     * Проверяет существование пользователя по идентификатору.
     *
     * @param id идентификатор пользователя
     * @return true, если пользователь существует
     */
    boolean isExist(long id);

    /**
     * Добавляет пользователя в друзья другому пользователю.
     * Дружба двунаправленная — оба пользователя получают друг друга в список друзей.
     *
     * @param userId идентификатор пользователя
     * @param friendId идентификатор пользователя, которого нужно добавить в друзья
     */
    void addFriend(long userId, long friendId);

    /**
     * Удаляет пользователя из списка друзей.
     * Удаление двунаправленное — оба пользователя удаляются из списков друзей друг друга.
     *
     * @param userId идентификатор пользователя
     * @param friendId идентификатор пользователя, которого нужно удалить из друзей
     */
    void removeFriend(long userId, long friendId);

    /**
     * Возвращает список общих друзей двух пользователей.
     *
     * @param userId идентификатор первого пользователя
     * @param friendId идентификатор второго пользователя
     * @return список пользователей, которые являются друзьями обоих
     */
    List<User> getCommonFriend(long userId, long friendId);

    /**
     * Возвращает список друзей пользователя.
     *
     * @param id идентификатор пользователя
     * @return список пользователей, которые имеют данного пользователя в списке друзей
     */
    List<User> getUserFriends(long id);
}
